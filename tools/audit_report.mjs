// Content audit of the language database. Goes BEYOND structural validation (tools/ci.mjs /
// scripts/validate_layouts.py) to assess keyboard CONTENT: does each layout actually carry the
// characters and Shift behaviour its writing system needs?
//
// Checks per language (none abort; they classify):
//   * caseful script with Latin letters that lack a distinct uppercase on Shift  -> MISSING_UPPERCASE
//   * caseless script with no distinct Shift/secondary layer                     -> NO_SECONDARY_LAYER
//   * layout whose base (normal) mapping is identical to another language        -> DUPLICATE_MAPPING
//   * manifest/file hasCase or field disagreement                                -> MANIFEST_MISMATCH
//   * provenance.verification not yet "branah-verified"                          -> NEEDS_VERIFICATION
//
// Writes docs/AUDIT_REPORT.md and prints a summary. Read-only; never mutates layouts or the manifest.
//
// Run:  node tools/audit_report.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANG_DIR = join(ROOT, "languages");
const MANIFEST = join(ROOT, "manifest.json");

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
const manifestById = new Map(manifest.languages.map((l) => [l.languageId, l]));

// A "letter" that genuinely has case (so a missing uppercase Shift is a real gap). Excludes caseless
// modifier/connector letters such as the Hausa glottal ʼ (U+02BC) which correctly map Shift -> self.
function isCasedLetter(ch) {
  if (!ch || [...ch].length !== 1) return false;
  const up = ch.toUpperCase();
  const lo = ch.toLowerCase();
  return up !== lo; // has a distinct upper/lower form
}

function distinctShiftLayer(rows) {
  for (const r of rows) for (const k of r.keys)
    if (k.shift && k.normal !== undefined && k.shift !== k.normal) return true;
  return false;
}

const records = [];
let englishSig = null;
const sigOwner = new Map();

for (const lang of readdirSync(LANG_DIR).filter((d) => statSync(join(LANG_DIR, d)).isDirectory()).sort()) {
  const dir = join(LANG_DIR, lang);
  for (const f of readdirSync(dir).filter((x) => x.endsWith(".json")).sort()) {
    const obj = JSON.parse(readFileSync(join(dir, f), "utf8"));
    const keys = obj.rows.flatMap((r) => r.keys);
    const normalSig = keys.map((k) => k.normal || "").join("|");
    if (obj.layoutId === "english-qwerty") englishSig = normalSig;
    const flags = [];

    // caseful Latin letters lacking a distinct uppercase
    if (obj.hasCase) {
      const missing = keys.filter((k) => isCasedLetter(k.normal) && (!k.shift || k.shift === k.normal));
      if (missing.length) flags.push(`MISSING_UPPERCASE(${missing.length})`);
    } else if (!distinctShiftLayer(obj.rows)) {
      flags.push("NO_SECONDARY_LAYER");
    }

    // manifest cross-check
    const mi = manifestById.get(lang);
    if (!mi) flags.push("NOT_IN_MANIFEST");
    else {
      if (!!mi.hasCase !== !!obj.hasCase) flags.push("MANIFEST_HASCASE_MISMATCH");
      if (!mi.layouts.some((l) => l.layoutId === obj.layoutId)) flags.push("LAYOUT_NOT_IN_MANIFEST");
    }

    const verification = (obj.provenance && obj.provenance.verification) || "unverified";
    if (verification !== "branah-verified") flags.push(`NEEDS_VERIFICATION(${verification})`);

    records.push({ lang, layoutId: obj.layoutId, script: obj.script, hasCase: !!obj.hasCase,
      normalSig, verification, flags });
  }
}

// duplicate base mappings (second+ occurrence flagged; english-copies called out separately)
for (const r of records) {
  if (sigOwner.has(r.normalSig)) {
    const owner = sigOwner.get(r.normalSig);
    r.flags.push(r.normalSig === englishSig ? `ENGLISH_QWERTY_COPY` : `DUPLICATE_OF(${owner})`);
  } else sigOwner.set(r.normalSig, r.lang);
}

const count = (pred) => records.filter(pred).length;
const has = (r, pre) => r.flags.some((f) => f.startsWith(pre));
const structural = records.filter((r) =>
  has(r, "MISSING_UPPERCASE") || has(r, "NO_SECONDARY_LAYER") || has(r, "MANIFEST") ||
  has(r, "NOT_IN_MANIFEST") || has(r, "LAYOUT_NOT_IN_MANIFEST"));
const needsVerify = records.filter((r) => has(r, "NEEDS_VERIFICATION"));

const lines = [];
lines.push("# Content audit report");
lines.push("");
lines.push("Generated by `tools/audit_report.mjs` (read-only). Structural/JSON validity is enforced");
lines.push("separately by `tools/ci.mjs`; this report assesses keyboard **content** adequacy.");
lines.push("");
lines.push("## Totals");
lines.push("");
lines.push(`- Layout files scanned: **${records.length}**`);
lines.push(`- Structurally/content-flagged (actionable): **${structural.length}**`);
lines.push(`  - Missing uppercase on a cased letter: ${count((r) => has(r, "MISSING_UPPERCASE"))}`);
lines.push(`  - Caseless with no secondary layer: ${count((r) => has(r, "NO_SECONDARY_LAYER"))}`);
lines.push(`  - Manifest disagreement: ${count((r) => has(r, "MANIFEST") || has(r, "NOT_IN_MANIFEST") || has(r, "LAYOUT_NOT_IN_MANIFEST"))}`);
lines.push(`- English-QWERTY copies (verify intentional vs. missing native chars): ${count((r) => has(r, "ENGLISH_QWERTY_COPY"))}`);
lines.push(`- Duplicate base mapping of another language: ${count((r) => has(r, "DUPLICATE_OF"))}`);
lines.push(`- Not yet branah-verified (expected: most are reviewed drafts): **${needsVerify.length}**`);
lines.push("");
lines.push("## Actionable flags (excluding the blanket verification flag)");
lines.push("");
lines.push("| Language | Layout | Script | Flags |");
lines.push("|----------|--------|--------|-------|");
for (const r of structural) {
  const fl = r.flags.filter((f) => !f.startsWith("NEEDS_VERIFICATION")).join(", ");
  lines.push(`| ${r.lang} | ${r.layoutId} | ${r.script} | ${fl} |`);
}
if (!structural.length) lines.push("| — | — | — | none |");
lines.push("");
lines.push("## English-QWERTY copies & duplicates (informational)");
lines.push("");
lines.push("Some are legitimate (languages that genuinely use the unmodified 26-letter Latin alphabet,");
lines.push("e.g. Somali, Oromo, Swahili; romanized input such as Pinyin/Jyutping). Others may indicate a");
lines.push("placeholder that still needs its native characters. Review each before promotion.");
lines.push("");
lines.push("| Language | Layout | Flag |");
lines.push("|----------|--------|------|");
for (const r of records.filter((r) => has(r, "ENGLISH_QWERTY_COPY") || has(r, "DUPLICATE_OF"))) {
  lines.push(`| ${r.lang} | ${r.layoutId} | ${r.flags.find((f) => f.startsWith("ENGLISH") || f.startsWith("DUPLICATE"))} |`);
}
lines.push("");
lines.push("## Verification backlog");
lines.push("");
lines.push("Per the repository's honesty policy, a layout is only \"verified\" after a manual key-by-key");
lines.push("comparison with its reference. Every layout except English is currently a reviewed draft or");
lines.push(`preview; **${needsVerify.length}** layouts carry a non-\`branah-verified\` status and need that review.`);
lines.push("");

const out = lines.join("\n");
writeFileSync(join(ROOT, "docs", "AUDIT_REPORT.md"), out, "utf8");
console.log(`audit: ${records.length} scanned, ${structural.length} actionable, ${needsVerify.length} need verification`);
console.log("wrote docs/AUDIT_REPORT.md");
for (const r of structural) console.log("  flag", r.lang, r.flags.filter((f) => !f.startsWith("NEEDS")).join(","));
